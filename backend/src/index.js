require("dotenv").config();
const express = require("express");
const cors = require("cors");
const helmet = require("helmet");
const rateLimit = require("express-rate-limit");
const { Pool } = require("pg");

const app = express();
const PORT = process.env.PORT || 5000;
const FRONTEND_ORIGIN = process.env.FRONTEND_ORIGIN || "http://localhost:5173";

app.disable("x-powered-by");
app.use(helmet());
app.use(cors({
  origin(origin, callback) {
    // Permit non-browser clients (curl/Postman) and the configured frontend.
    if (!origin || origin === FRONTEND_ORIGIN) return callback(null, true);
    return callback(new Error("Origin is not allowed by CORS"));
  },
  methods: ["GET", "POST", "DELETE", "OPTIONS"],
  allowedHeaders: ["Content-Type", "X-Trip-Id"]
}));
app.use(express.json({ limit: "40kb" }));
app.use("/api", rateLimit({ windowMs: 60_000, limit: 90, standardHeaders: "draft-7", legacyHeaders: false }));

const databaseUrl = process.env.DATABASE_URL;
if (!databaseUrl) {
  console.error("DATABASE_URL is missing. Copy .env.example to .env and configure PostgreSQL.");
  process.exit(1);
}
const isHostedDb = !/localhost|127\.0\.0\.1/.test(databaseUrl);
const pool = new Pool({
  connectionString: databaseUrl,
  ssl: isHostedDb ? { rejectUnauthorized: false } : false,
  connectionTimeoutMillis: 10000
});

const WIKI_API = "https://en.wikipedia.org/w/api.php";
const USER_AGENT = "TripWiseStudentProject/1.0 (educational travel planner)";
const allowedCategories = new Set(["all", "city", "nature", "culture", "landmark"]);
const allowedSorts = new Set(["relevance", "name-asc", "name-desc"]);

function cleanText(value, max = 700) {
  return typeof value === "string" ? value.trim().replace(/\s+/g, " ").slice(0, max) : "";
}
function tripIdFrom(req) {
  const id = req.get("X-Trip-Id") || "";
  // UUID generated by crypto.randomUUID in the browser.
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(id) ? id : null;
}
function categoryFor(title, description) {
  const s = `${title} ${description}`.toLowerCase();
  if (/\b(mountain|national park|waterfall|island|forest|lake|beach|desert|valley|river|glacier|wildlife|volcano)\b/.test(s)) return "nature";
  if (/\b(museum|temple|palace|monument|heritage|culture|historic|historical|archaeological|cathedral|fort)\b/.test(s)) return "culture";
  if (/\b(tower|bridge|statue|landmark|building|castle|colosseum|pyramid)\b/.test(s)) return "landmark";
  if (/\b(city|town|capital|municipality|metropolitan)\b/.test(s)) return "city";
  return "city";
}
function normalizePage(page) {
  const title = cleanText(page.title, 180);
  const description = cleanText(page.extract || "Discover this destination and learn more from its Wikipedia article.", 700);
  const image = page.thumbnail?.source || "";
  return {
    id: title,
    title,
    description,
    image,
    url: `https://en.wikipedia.org/wiki/${encodeURIComponent(title.replace(/ /g, "_"))}`,
    category: categoryFor(title, description),
    location: "Explore the world"
  };
}
async function wikiFetch(params) {
  const url = new URL(WIKI_API);
  Object.entries({ ...params, format: "json", origin: "*" }).forEach(([key, value]) => url.searchParams.set(key, String(value)));
  const response = await fetch(url, { headers: { "User-Agent": USER_AGENT }, signal: AbortSignal.timeout(12000) });
  if (!response.ok) throw new Error(`Wikimedia returned HTTP ${response.status}`);
  return response.json();
}
function asyncRoute(fn) {
  return (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
}

async function initDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS itinerary_items (
      id BIGSERIAL PRIMARY KEY,
      trip_id UUID NOT NULL,
      wikipedia_title TEXT NOT NULL,
      title TEXT NOT NULL,
      description TEXT NOT NULL DEFAULT '',
      image TEXT NOT NULL DEFAULT '',
      url TEXT NOT NULL,
      category TEXT NOT NULL DEFAULT 'city',
      location TEXT NOT NULL DEFAULT 'Explore the world',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (trip_id, wikipedia_title)
    );
    CREATE INDEX IF NOT EXISTS itinerary_items_trip_id_idx ON itinerary_items(trip_id);
  `);
}

app.get("/health", asyncRoute(async (_req, res) => {
  await pool.query("SELECT 1");
  res.json({ status: "ok", database: "connected" });
}));

app.get("/api/destinations", asyncRoute(async (req, res) => {
  const q = cleanText(req.query.q, 120);
  const category = cleanText(req.query.category || "all", 20).toLowerCase();
  const sort = cleanText(req.query.sort || "relevance", 20).toLowerCase();
  const page = Math.max(1, Math.min(20, Number.parseInt(req.query.page, 10) || 1));
  const limit = Math.max(1, Math.min(24, Number.parseInt(req.query.limit, 10) || 12));
  if (!allowedCategories.has(category)) return res.status(400).json({ error: "Invalid category filter." });
  if (!allowedSorts.has(sort)) return res.status(400).json({ error: "Invalid sort option." });
  const searchTerm = q || "best travel destinations famous places";
  const data = await wikiFetch({
    action: "query", generator: "search", gsrsearch: `${searchTerm} (travel OR tourism OR destination)`,
    gsrnamespace: 0, gsrlimit: Math.min(50, Math.max(20, limit * 2)), gsroffset: (page - 1) * limit,
    prop: "pageimages|extracts", piprop: "thumbnail", pithumbsize: 700,
    exintro: 1, explaintext: 1, exchars: 900
  });
  let items = Object.values(data.query?.pages || {}).map(normalizePage)
    .filter(item => item.title && item.description);
  if (category !== "all") items = items.filter(item => item.category === category);
  if (sort === "name-asc") items.sort((a, b) => a.title.localeCompare(b.title));
  if (sort === "name-desc") items.sort((a, b) => b.title.localeCompare(a.title));
  res.json({ items: items.slice(0, limit), page, limit, total: items.length, source: "Wikimedia" });
}));

app.get("/api/destinations/:title", asyncRoute(async (req, res) => {
  const title = cleanText(decodeURIComponent(req.params.title), 180);
  if (!title) return res.status(400).json({ error: "Destination title is required." });
  const data = await wikiFetch({
    action: "query", prop: "pageimages|extracts|info", titles: title,
    piprop: "thumbnail", pithumbsize: 1000, exintro: 1, explaintext: 1, exchars: 4000, inprop: "url"
  });
  const page = Object.values(data.query?.pages || {})[0];
  if (!page || page.missing !== undefined) return res.status(404).json({ error: "Destination not found." });
  const item = normalizePage(page);
  item.url = page.fullurl || item.url;
  item.description = cleanText(page.extract || item.description, 3500);
  res.json(item);
}));

app.get("/api/itinerary", asyncRoute(async (req, res) => {
  const tripId = tripIdFrom(req);
  if (!tripId) return res.status(400).json({ error: "A valid X-Trip-Id UUID header is required." });
  const result = await pool.query(
    `SELECT wikipedia_title AS id, title, description, image, url, category, location, created_at
     FROM itinerary_items WHERE trip_id = $1 ORDER BY created_at ASC`, [tripId]
  );
  res.json({ items: result.rows });
}));

app.post("/api/itinerary", asyncRoute(async (req, res) => {
  const tripId = tripIdFrom(req);
  if (!tripId) return res.status(400).json({ error: "A valid X-Trip-Id UUID header is required." });
  const body = req.body || {};
  const title = cleanText(body.title, 180);
  const description = cleanText(body.description, 700);
  const image = cleanText(body.image, 1000);
  const url = cleanText(body.url, 1000);
  const category = cleanText(body.category || "city", 30);
  const location = cleanText(body.location || "Explore the world", 120);
  const id = cleanText(body.id || title, 180);
  if (!title || !url || !/^https:\/\/en\.wikipedia\.org\//.test(url)) {
    return res.status(400).json({ error: "A destination title and valid Wikipedia URL are required." });
  }
  if (image && !/^https:\/\//.test(image)) return res.status(400).json({ error: "Image URL must use HTTPS." });
  try {
    const result = await pool.query(
      `INSERT INTO itinerary_items (trip_id, wikipedia_title, title, description, image, url, category, location)
       VALUES ($1,$2,$3,$4,$5,$6,$7,$8)
       RETURNING wikipedia_title AS id, title, description, image, url, category, location, created_at`,
      [tripId, id, title, description, image, url, category, location]
    );
    res.status(201).json({ item: result.rows[0], message: "Destination added to your trip." });
  } catch (error) {
    if (error.code === "23505") return res.status(409).json({ error: "This destination is already in your trip." });
    throw error;
  }
}));

app.delete("/api/itinerary/:title", asyncRoute(async (req, res) => {
  const tripId = tripIdFrom(req);
  if (!tripId) return res.status(400).json({ error: "A valid X-Trip-Id UUID header is required." });
  const title = cleanText(decodeURIComponent(req.params.title), 180);
  const result = await pool.query(
    "DELETE FROM itinerary_items WHERE trip_id = $1 AND wikipedia_title = $2 RETURNING wikipedia_title",
    [tripId, title]
  );
  if (!result.rowCount) return res.status(404).json({ error: "That destination is not in your itinerary." });
  res.json({ message: "Destination removed from your trip." });
}));

app.use((req, res) => res.status(404).json({ error: `Route not found: ${req.method} ${req.path}` }));
app.use((err, _req, res, _next) => {
  console.error(err);
  if (err.message === "Origin is not allowed by CORS") return res.status(403).json({ error: "This website origin is not allowed by the API." });
  if (err.name === "AbortError" || err.name === "TimeoutError") return res.status(504).json({ error: "The destination service took too long to respond. Please try again." });
  if (err.message?.includes("Wikimedia returned HTTP")) return res.status(502).json({ error: "The external destination service is temporarily unavailable." });
  res.status(500).json({ error: "Something went wrong on the server. Please try again." });
});

initDatabase().then(() => {
  app.listen(PORT, () => console.log(`TripWise API listening on port ${PORT}`));
}).catch(error => {
  console.error("Could not initialize database:", error.message);
  process.exit(1);
});
